"""Checks for the Relative AAM product `rel_aam` (TEST ONLY).

Runs entirely offline: it serves the synthetic PSL files written by
tests/aam_synthetic.py on a local port and points the app at them through
PSL_BASE_URL, then drives the *real* product path (addon registry -> compute ->
render -> /generate), so every line shipped in custom/rel_aam.py is executed.

    python tests/aam_synthetic.py
    python tests/check_rel_aam.py

Checks
  1. the shipped integrator reproduces the closed-form AAM of a known field
     (u = U0 cos^2 phi) row by row and globally,
  2. the product is registered and shows up in the Hovmöller sidebar group,
  3. the internal bookkeeping is exact: the latitude field integrates to the
     global Mr, the anomaly is field − climatology, M and dM/dt follow their
     definitions, and the time smoothing is a plain running mean,
  4. the field agrees with an independent full-resolution quadrature of the
     same file, column by column (latitude profile) and globally,
  5. /generate returns a real PNG,
  6. the GWO product's committed climatology cache is left untouched,
  7. short and cross-year windows still render.
"""
