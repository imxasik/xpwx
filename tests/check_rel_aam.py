R_EARTH, GRAV = 6.371e6, 9.80665
OK = True


def check(label, good, detail=""):
    global OK
    OK = OK and bool(good)
    print(f"   [{'PASS' if good else 'FAIL'}] {label}" + (f"   {detail}" if detail else ""))


