def independent_lat_field(path, index=-1, stride=1):
    """(lat_rad ascending, AAM per radian) of one record, integrated with numpy
    quadrature written from scratch (no product code).  ``stride`` subsamples the
    latitude/longitude grid exactly like the product's LAT_STRIDE/LON_STRIDE."""
    ds = netCDF4.Dataset(path)
    u = np.ma.filled(ds["uwnd"][index], 0.0).astype(np.float64)      # (lev, lat, lon)
    p = np.asarray(ds["level"][:], dtype=float) * 100.0
    lat = np.deg2rad(np.asarray(ds["lat"][:], dtype=float))[::stride]
    lon = np.deg2rad(np.asarray(ds["lon"][:], dtype=float))[::stride]
    u = u[:, ::stride, ::stride]
    order = np.argsort(lat)
    lat, u = lat[order], u[:, order, :]
    i_p = -np.trapezoid(u, p, axis=0)                                # (lat, lon)
    i_p_ext = np.concatenate([i_p, i_p[:, :1]], axis=1)
    lon_ext = np.concatenate([lon, [lon[0] + 2 * np.pi]])
    i_lon = np.trapezoid(i_p_ext, lon_ext, axis=1)                   # (lat,)
    ds.close()
    return lat, (R_EARTH ** 3 / GRAV) * i_lon * np.cos(lat) ** 2


def analytic_case():
    """u = U0 cos^2(phi) everywhere -> closed-form AAM per latitude and globally."""
    U0 = 8.0
    lev = np.array([1000, 850, 700, 500, 300, 200, 100, 50], float)
    lat = np.linspace(90, -90, 73)[::2]
    lon = np.arange(0, 360, 2.5)[::2]
    gc = GWO.build_grid_constants(lev, lat, lon)

    phi = np.deg2rad(lat)[:, None]
    field = U0 * np.cos(phi) ** 2 * np.ones((1, lev.size, lat.size, lon.size))

    dp = (lev.max() - lev.min()) * 100.0
    k = (R_EARTH ** 3 / GRAV) * U0 * dp * (2 * np.pi)
    lat_sorted = np.rad2deg(gc["lat_sorted"])
    exact = k * np.cos(gc["lat_sorted"]) ** 4                  # per radian of latitude
    total = np.trapezoid(exact, gc["lat_sorted"])              # closed form, globally

    got_lat = RA.lat_field(field, gc)[0]
    got_total = RA.integrate_field(got_lat[None, :], gc)[0]
    return lat_sorted, exact, total, got_lat, got_total


def png_size(data):
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        return None
    w, h = struct.unpack(">II", data[16:24])
    return w, h


def main():
    spec = json.load(open(TRUTH))
    print(f"synthetic window {spec['start']} → {spec['end']} "
          f"({spec['n_days']} days), mirror {os.environ['PSL_BASE_URL']}\n")

    # ---- 1. closed-form integration --------------------------------------
    print("1. integrator vs closed form  (u = U0 cos^2 phi)")
    lat_deg, exact_lat, exact_total, got_lat, got_total = analytic_case()
    row_rel = np.abs(got_lat - exact_lat) / np.abs(exact_lat)
    check("latitude profile (per row)", bool(np.all(row_rel < 1e-9)),
          f"max rel err {row_rel.max():.1e}")
    rel = abs(got_total - exact_total) / abs(exact_total)
    check("global AAM = latitude integral of the profile",
          rel < 1e-9, f"got {got_total:.6e}  exact {exact_total:.6e}  rel {rel:.1e}")

    # ---- 2. registry / sidebar -------------------------------------------
    print("\n2. sidebar registration")
    check("rel_aam in the product registry", "rel_aam" in metmap.PRODUCTS)
    pkg = metmap.PRODUCTS["rel_aam"]
    check("tag is Hovmöller", pkg["tag"] == "Hovmöller", f"tag={pkg['tag']}")
    grp = [g for g in metmap.group_products() if g["tag"] == "Hovmöller"]
    ids = [p["id"] for p in grp[0]["product_list"]] if grp else []
    check("listed under the Hovmöller group", "rel_aam" in ids, f"group={ids}")
    with flask_app.app.test_client() as cli:
        r = cli.get("/products")
        body = r.get_json()
    listed = [p["id"] for p in body["products"]]
    check("/products endpoint serves it", r.status_code == 200 and "rel_aam" in listed)

    # ---- 3. compute: internal consistency --------------------------------
    print("\n3. compute path")
    dates = engine._resolve_dates("auto", None, config.DEFAULT_N_DAYS)
    lat, lon, d = pro_compute.compute(pkg, dates)
    n = len(d["times"])
    check("window length", n == pkg["window"], f"{n} days")
    check("ends on the dataset's last day",
          d["times"][-1].date().isoformat() == spec["end"], d["times"][-1].isoformat())
    for k in ("field", "clim", "anom", "mr", "anom_tot", "M", "dMdt"):
        check(f"no NaN / inf in '{k}'", bool(np.all(np.isfinite(d[k]))))
    lat_rad = np.deg2rad(np.asarray(d["lat_axis"], float))
    check("latitude axis is ascending and spans the poles",
          bool(np.all(np.diff(d["lat_axis"]) > 0)
               and abs(d["lat_axis"][0] + 90) < 1e-6 and abs(d["lat_axis"][-1] - 90) < 1e-6))
    glob = np.trapezoid(np.asarray(d["field"], float), lat_rad, axis=1)
    rel = np.max(np.abs(glob - d["mr"])) / np.max(np.abs(d["mr"]))
    check("latitude field integrates to the global Mr", rel < 1e-12,
          f"max rel diff {rel:.1e}")
    clim_glob = np.trapezoid(np.asarray(d["clim"], float), lat_rad, axis=1)
    rel = np.max(np.abs(clim_glob - d["mr_clim"])) / np.max(np.abs(d["mr_clim"]))
    check("climatology integrates to the climatological Mr", rel < 1e-12,
          f"max rel diff {rel:.1e}")
    check("anomaly = smoothed field − climatology",
          np.allclose(d["anom"], d["field"] - d["clim"], rtol=1e-12, atol=0.0))
    check("global anomaly = Mr − Mr(clim)",
          np.allclose(d["anom_tot"], d["mr"] - d["mr_clim"], rtol=1e-12, atol=0.0))
    check("M = anomaly / sigma_M",
          np.allclose(d["M"], d["anom_tot"] / GWO.AAM_STD, rtol=1e-12, atol=0.0))
    check("dM/dt = grad(Mr) / sigma_tend",
          np.allclose(d["dMdt"], np.gradient(d["mr"], 86400.0) / GWO.TEND_STD,
                      rtol=1e-12, atol=0.0))
    hu = d["mr"] / RA.HU
    check("Mr in a physically plausible range", bool(np.all((hu > 3) & (hu < 40))),
          f"{hu.min():.2f} – {hu.max():.2f} HU")
    shade = np.asarray(d["anom"]) * RA.DEG / RA.FIELD_UNIT
    # the synthetic case is deliberately a strong-event case: it should fill the
    # palette out to its end colours without everything saturating
    frac = float(np.mean(np.abs(shade) > 0.5))
    check("the shading uses a good part of the ±2 × 10²⁴ palette",
          1.0 < float(np.max(np.abs(shade))) < 6.0 and 0.08 < frac < 0.6,
          f"max |anom| = {np.max(np.abs(shade)):.2f} × 10²⁴, "
          f"{100 * frac:.0f}% of the area beyond ±0.5")
    peak = float(np.max(np.abs(np.asarray(d["field"]) * RA.DEG / RA.FIELD_UNIT)))
    ci = RA.nice_ci(peak)
    check("contour interval gives a readable number of lines",
          3.0 <= peak / ci <= 9.0 or ci == RA.CI_CHOICES[-1],
          f"peak {peak:.2f}, CI = {ci:g} × 10²⁴ -> {peak / ci:.1f} lines")
    # the same rule must stay readable for the real data's weaker field
    for real_peak in (0.4, 1.2, 2.5):
        real_ci = RA.nice_ci(real_peak)
        check(f"contour interval for a peak of {real_peak:g} × 10²⁴",
              3.0 <= real_peak / real_ci <= 9.0,
              f"CI = {real_ci:g} × 10²⁴ -> {real_peak / real_ci:.1f} lines")

    # smoothing is a renormalised running mean: constants survive, the interior
    # is the plain boxcar, and the day-to-day variance drops
    raw = np.asarray(d["field"], float)
    flat = np.ones_like(raw) * 7.0
    check("time smoothing leaves a constant field unchanged",
          np.allclose(RA.smooth_time(flat, 5), flat, rtol=1e-12, atol=1e-12))
    sm = RA.smooth_time(raw, 5)
    interior = slice(3, raw.shape[0] - 3)
    plain = np.stack([np.convolve(raw[:, k], np.ones(5) / 5, mode="valid")
                      for k in range(raw.shape[1])], axis=1)[1:-1]
    check("interior smoothing is the plain 5-day mean",
          np.allclose(sm[interior], plain, rtol=1e-10, atol=0.0))
    check("time smoothing reduces the day-to-day variance",
          float(np.mean(np.var(np.diff(sm, axis=0), axis=0)))
          < float(np.mean(np.var(np.diff(raw, axis=0), axis=0))))
    check("cyclic smoothing keeps the annual climatology mean",
          abs(float(RA.cyclic_running_mean(np.arange(365.0), 31).mean())
              - float(np.arange(365.0).mean())) < 1e-9)

    # ---- 4. independent quadrature of the same file ----------------------
    print("\n4. independent full-resolution quadrature")
    path = os.path.join(SERVE_ROOT, "Datasets", "ncep", f"uwnd.{spec['year']}.nc")
    # compare against the UNSMOOTHED product field (smooth_days = 1)
    _, _, d1 = pro_compute.compute(dict(pkg, smooth_days=1), dates)
    prof_p = np.asarray(d1["field"], float)[-1]

    # (a) implementation: the same grid the product uses (stride 2), so only the
    #     quadrature itself is under test
    lat_s, prof_s = independent_lat_field(path, -1, stride=GWO.LAT_STRIDE)
    # the AAM per degree vanishes at the poles (cos^2 phi), so a purely relative
    # test needs a floor; 1e-6 of the peak is far below any real signal
    floor_s = 1e-6 * float(np.max(np.abs(prof_s)))
    row_rel = np.abs(prof_p - prof_s) / np.maximum(np.abs(prof_s), floor_s)
    # 1e-6 leaves room for the packed data being unpacked with the file's float32
    # scale factor rather than in double precision
    check("latitude profile matches the independent integral on the same grid",
          float(np.max(row_rel)) < 1e-6, f"max rel err {np.max(row_rel):.1e}")

    # (b) discretisation: the full 2.5-degree grid, which the product subsamples
    lat_f, prof_f = independent_lat_field(path, -1, stride=1)
    lat_p = np.deg2rad(np.asarray(d1["lat_axis"], float))
    prof_f_on_p = np.interp(lat_p, lat_f, prof_f)
    floor = 0.02 * float(np.max(np.abs(prof_f_on_p)))
    row_rel = np.abs(prof_p - prof_f_on_p) / np.maximum(np.abs(prof_f_on_p), floor)
    check("stride-2 sampling stays close to the full-resolution profile",
          float(np.max(row_rel)) < 0.20,
          f"max {np.max(row_rel):.1%} of the local value, median {np.median(row_rel):.1%}")
    tot_f = float(np.trapezoid(prof_f, lat_f))
    rel = abs(d1["mr"][-1] - tot_f) / abs(tot_f)
    check("global value of the last day vs the full-resolution integral", rel < 0.03,
          f"product {d1['mr'][-1]:.6e}  independent {tot_f:.6e}  rel {rel:.2%}")

    # ---- 5. render through the real endpoint -----------------------------
    print("\n5. /generate end to end")
    with flask_app.app.test_client() as cli:
        r = cli.post("/generate", json={"product": "rel_aam", "mode": "auto"})
    body = r.data
    check("HTTP 200", r.status_code == 200, f"status {r.status_code}")
    size = png_size(body)
    check("valid PNG", size is not None, f"{len(body) / 1e6:.2f} MB, {size}")
    # square, like the reference AAM chart
    check("figure is square and high resolution",
          size is not None and size[0] == size[1] and size[0] >= 1200, f"{size}")
    out = os.environ.get("OUT_PNG", "/tmp/rel_aam_preview.png")
    with open(out, "wb") as fh:
        fh.write(body)
    print(f"   wrote {out}")

    # ---- 6. the GWO cache must not be touched ----------------------------
    print("\n6. shared caches")
    if CACHE_HASH_BEFORE is not None:
        after = hashlib.sha256(open(GWO_CACHE, "rb").read()).hexdigest()
        check("ltm_aam_cache.npy unchanged", after == CACHE_HASH_BEFORE)
    check("climatology cached under data_cache/ (git-ignored)",
          os.path.exists(RA.LTM_CACHE) and RA.LTM_CACHE.startswith(config.CACHE_DIR),
          RA.LTM_CACHE)

    # ---- 7. short / cross-year windows still render -----------------------
    print("\n7. short and cross-year windows")
    for label, end in (("short window (file starts later)", "2026-06-30"),
                       ("window stitched from two files", "2025-12-20")):
        with flask_app.app.test_client() as cli:
            r = cli.post("/generate", json={"product": "rel_aam", "mode": "manual",
                                            "date": end})
        size = png_size(r.data) if r.status_code == 200 else None
        check(label, r.status_code == 200 and size is not None,
              f"status {r.status_code}, {size}")

    print("\nRESULT", "PASS" if OK else "FAIL")
    if _HTTPD is not None:
        _HTTPD.shutdown()
    return 0 if OK else 1


if __name__ == "__main__":
    sys.exit(main())
